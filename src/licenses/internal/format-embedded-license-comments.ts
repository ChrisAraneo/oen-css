import { isEmpty, join, map } from 'lodash-es';
import { match } from 'ts-pattern';
import type { LicenseComment } from '../../banner/types/license-comment.ts';
import { formatEmbeddedLicenseComment } from './format-embedded-license-comment.ts';

export const formatEmbeddedLicenseComments = (
  comments: readonly LicenseComment[],
): string =>
  match(isEmpty(comments))
    .with(true, () => '')
    .otherwise(
      () => `
## Notices embedded in the stylesheets

Bulma vendors the components below directly into its Sass sources, together with their own notices. Those
notices survive compilation and minification, so they reach you inside the stylesheet itself. They are
listed here because they are part of what the package distributes. This section is generated by reading the
license comments back out of the built \`oen.css\`, so it cannot fall out of step with the artifact.

${join(
  map(comments, (comment) => formatEmbeddedLicenseComment(comment)),
  '\n',
)}`,
    );
